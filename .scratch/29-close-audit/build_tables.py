"""Generate evidence routers from retained raw selections and revision identities."""
from pathlib import Path
import json

HOME=Path(__file__).resolve().parent
samples=json.loads((HOME/'samples.json').read_text())
aliases={}
for s in samples:
    short=s['task'].split('-')[0]+s['task'].split('-')[1]
    if s['arm']=='r2-full':
        alias='R2A05'
    else:
        alias=('O' if s['arm']=='ours' else 'P')+short
        if short=='T26' and s['arm']=='pi':alias += 'good' if s['actual'] else 'bad'
    aliases[alias]='evidence/'+s['id']
(HOME/'sample-map.json').write_text(json.dumps(aliases,indent=2)+'\n')
lines=['# Sample router (generated by build_tables.py; edit selection in collect_evidence.py)', '| alias | final measurement raw row | retained directory | actual / claimed |', '| --- | --- | --- | --- |']
for s in samples:
    alias=next(a for a,v in aliases.items() if v=='evidence/'+s['id'])
    lines.append(f'| {alias} | `{s["source_results"]}:{s["source_line"]}` | [{s["id"]}](evidence/{s["id"]}/index.md) | {s["actual"]} / {s["claimed"]} |')
(HOME/'sample-router.md').write_text('\n'.join(lines)+'\n')
lines=['# Literal source-write revisions (generated by build_tables.py)', 'All source-write SHA256 values match literal model payloads. Each intermediate external-grader outcome is **unknown** unless its bytes match the retained final graded source; no grader rerun was made.', '| sample | trajectory line | path | SHA256 | payload line | equals graded final bytes |', '| --- | --- | --- | --- | --- | --- |']
for r in json.loads((HOME/'reconstruction.json').read_text()):
    alias=next(a for a,v in aliases.items() if v=='evidence/'+r['id'])
    d=HOME/'evidence'/r['id']
    for w in r['writes']:
        g=d/'grade-repo'/w['path']
        import hashlib
        same=g.is_file() and hashlib.sha256(g.read_bytes()).hexdigest()==w['sha256']
        lines.append(f'| {alias} | {w["trajectory_line"]} | `{w["path"]}` | `{w["sha256"]}` | {w["payload_line"]} | {same} |')
(HOME/'revision-table.md').write_text('\n'.join(lines)+'\n')
print(f'{len(aliases)} aliases; {len(lines)-4} write revisions routed')
