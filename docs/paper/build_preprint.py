#!/usr/bin/env python3
"""Build ``docs/paper/preprint.md`` — the paper as one read form — from the authored sections.

    python3 docs/paper/build_preprint.py            # rewrite the render
    python3 docs/paper/build_preprint.py --check    # is the committed render current?

The paper has one source of truth per section: the authored files ``00-abstract.md`` and
``01-problem.md`` … ``08-reproduce.md``, plus ``numbers.md`` as the appendix. ``preprint.md`` is a
**render**: it holds no sentence that is not in one of those files, so editing it by hand is a
change that the next build erases. Its own header says so, and ``--check`` catches a stale render
by naming the first line that differs instead of leaving a reader to compare two copies.

No network, no model, no numbers of its own: the counts this prints are computed here and are not
written into the render, so the two cannot drift.
"""
from __future__ import annotations

import sys
from pathlib import Path

PAPER = Path(__file__).resolve().parent
RENDER = PAPER / "preprint.md"

TITLE = ("Whatever the harness bought: a pre-registered measurement of a program-shaped coding "
         "harness on a small local model, with its negative results kept")
SECTIONS = ["00-abstract.md", "01-problem.md", "02-protocol.md", "03-result-r1.md",
            "04-result-r3.md", "05-result-r2.md", "06-negative-results.md", "07-limits.md",
            "08-reproduce.md"]
APPENDIX = "numbers.md"
APPENDIX_HEADING = "Appendix A — every number, its source, and the command that re-derives it"

PREAMBLE = f"""<!-- kind: render — generated by `python3 docs/paper/build_preprint.py`; do not edit by hand.
     Sources, in order: docs/paper/{{{','.join(SECTIONS)}}} and {APPENDIX} as the appendix.
     Check: `python3 docs/paper/build_preprint.py --check` names the first stale line. -->

# {TITLE}

Draft for reading, not a publication: no DOI, no submission, no push.
Every decisive number below was measured once, on revision `45ebb32`, and re-derives from the
repository alone with `python3 reproduce.py` (§8).
"""


def body(name: str, mode: str) -> str:
    """The file's text with every heading pushed one level down, so the render has one title.

    A section keeps its H1 as an H2 and its subsections as H3, which is the hierarchy the
    authored files already carry. The appendix drops its own H1 (the appendix heading is the
    builder's) and shifts the rest the same way, so nothing nests under the wrong parent.
    """
    path = PAPER / name
    if not path.is_file():
        raise SystemExit(f"build_preprint: missing source {path.relative_to(PAPER.parent.parent)} — "
                         "the render is built from the authored sections and cannot invent one")
    lines = path.read_text(encoding="utf-8").rstrip("\n").splitlines()
    if mode == "appendix" and lines and lines[0].startswith("# "):
        lines = lines[1:]
    return "\n".join(("#" + ln) if ln.startswith("#") else ln for ln in lines)


def build() -> str:
    parts = [PREAMBLE.rstrip("\n")]
    outline: list[str] = []
    for name in SECTIONS:
        text = body(name, "section")
        head = next((ln for ln in text.splitlines() if ln.startswith("## ")), "")
        outline.append(head[3:])
        parts.append(text)
    parts.append(f"## {APPENDIX_HEADING}\n")
    parts.append(body(APPENDIX, "appendix"))
    outline.append(APPENDIX_HEADING)
    # The outline is computed from the headings, so it cannot drift from them.
    contents = "## Contents\n\n" + "\n".join(f"- {head}" for head in outline)
    parts.insert(1, contents)
    return "\n\n".join(parts) + "\n"


def main(argv: list[str]) -> int:
    text = build()
    words = len(text.split())
    if "--check" in argv:
        if not RENDER.is_file():
            print(f"preprint.md: absent — run `python3 docs/paper/build_preprint.py` to write it")
            return 1
        have = RENDER.read_text(encoding="utf-8").splitlines()
        want = text.splitlines()
        for i, (a, b) in enumerate(zip(have, want), start=1):
            if a != b:
                print(f"preprint.md: stale — first difference at line {i}")
                print(f"  committed: {a[:160]}")
                print(f"  built:     {b[:160]}")
                return 1
        if len(have) != len(want):
            print(f"preprint.md: stale — {len(have)} lines committed, {len(want)} built, "
                  "identical up to line " f"{min(len(have), len(want))}")
            return 1
        print(f"preprint.md: current — {len(want)} lines, {words} words, "
              f"{len(SECTIONS)} sections plus the numbers appendix")
        return 0
    RENDER.write_text(text, encoding="utf-8")
    print(f"preprint.md: written — {len(text.splitlines())} lines, {words} words, "
          f"{len(SECTIONS)} sections plus the numbers appendix")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
